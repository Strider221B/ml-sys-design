import { TelemetryConstants } from '@/core/telemetry/telemetry_constants';
import { WorkspaceDocument, WorkspaceNode } from '@/core/state/workspace_types';

export interface TerraformExportOptions {
  provider?: 'aws' | 'gcp' | 'kubernetes';
  environment?: 'dev' | 'staging' | 'prod';
  includeOutputs?: boolean;
}

/**
 * Compiles canvas workspace graphs into production-ready Terraform HCL infrastructure.
 */
export class TerraformHclExporter {
  private static readonly _HEADER_COMMENT = '# Auto-generated by 2026 ML System Design Platform\n';
  private static readonly _TERRAFORM_VERSION = TelemetryConstants.DEFAULT_TERRAFORM_VERSION;
  private static readonly _DEFAULT_ENV = 'prod';
  private static readonly _DEFAULT_PROVIDER = 'aws';

  public constructor() {}

  /**
   * Compiles the workspace document architecture into valid Terraform HCL string.
   */
  public exportHcl(document: WorkspaceDocument, options?: TerraformExportOptions): string {
    const env = options?.environment ?? TerraformHclExporter._DEFAULT_ENV;
    const parts: string[] = [
      TerraformHclExporter._HEADER_COMMENT,
      `# Workspace: ${document.title} (Environment: ${env})\n\n`,
      this._generateTerraformBlock(),
    ];

    for (const node of document.nodes) {
      parts.push(this._generateNodeResource(node, env));
    }

    if (options?.includeOutputs) {
      parts.push(this._generateOutputs(document));
    }

    return parts.join('\n');
  }

  /**
   * Performs basic syntax integrity checks on generated Terraform HCL.
   */
  public validateHclSyntax(hcl: string): boolean {
    if (!hcl || hcl.trim().length === 0) return false;
    const openBraces = (hcl.match(/\{/g) || []).length;
    const closeBraces = (hcl.match(/\}/g) || []).length;
    if (openBraces !== closeBraces) return false;
    return hcl.includes('terraform {') && hcl.includes('resource ');
  }

  /**
   * Returns list of supported canvas node types mapped to Terraform resources.
   */
  public getSupportedResourceTypes(): readonly string[] {
    return [
      'INGRESS_GATEWAY',
      'VLLM_INFERENCE_ENGINE',
      'VECTOR_DATABASE',
      'FEATURE_STORE',
      'CACHING_LAYER',
      'SAFETY_GUARDRAIL',
    ];
  }

  private _generateTerraformBlock(): string {
    return `terraform {
  required_version = "${TerraformHclExporter._TERRAFORM_VERSION}"
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = "~> 5.0"
    }
    kubernetes = {
      source  = "hashicorp/kubernetes"
      version = "~> 2.30"
    }
  }
}
`;
  }

  private _generateNodeResource(node: WorkspaceNode, env: string): string {
    switch (node.type) {
      case 'INGRESS_GATEWAY':
        return this._buildIngressGatewayHcl(node, env);
      case 'VLLM_INFERENCE_ENGINE':
        return this._buildVllmInferenceHcl(node, env);
      case 'VECTOR_DATABASE':
        return this._buildVectorDatabaseHcl(node, env);
      case 'FEATURE_STORE':
      case 'CACHING_LAYER':
        return this._buildRedisClusterHcl(node, env);
      case 'SAFETY_GUARDRAIL':
        return this._buildWafGuardrailHcl(node, env);
      default:
        return this._buildGenericInstanceHcl(node, env);
    }
  }

  private _buildIngressGatewayHcl(node: WorkspaceNode, env: string): string {
    const resId = this._sanitizeId(node.id);
    return `resource "aws_lb" "${resId}" {
  name               = "${resId}-${env}"
  internal           = false
  load_balancer_type = "application"
  tags = {
    Environment = "${env}"
    ManagedBy   = "ML-Sys-Design"
  }
}
`;
  }

  private _buildVllmInferenceHcl(node: WorkspaceNode, env: string): string {
    const resId = this._sanitizeId(node.id);
    const instanceType = node.data.hardwareProfile ?? 'g5.12xlarge';
    return `resource "aws_instance" "${resId}" {
  ami           = "ami-0c55b159cbfafe1f0"
  instance_type = "${instanceType}"
  user_data     = <<-EOF
    #!/bin/bash
    docker run --gpus all -d -p 8000:8000 vllm/vllm-openai:latest
  EOF
  tags = {
    Name        = "${node.data.label}"
    Environment = "${env}"
  }
}
`;
  }

  private _buildVectorDatabaseHcl(node: WorkspaceNode, env: string): string {
    const resId = this._sanitizeId(node.id);
    return `resource "helm_release" "${resId}" {
  name       = "${resId}-${env}"
  repository = "https://qdrant.github.io/qdrant-helm"
  chart      = "qdrant"
  values = [
    yamlencode({
      replicaCount = 3
      resources = { limits = { memory = "32Gi", cpu = "8" } }
    })
  ]
}
`;
  }

  private _buildRedisClusterHcl(node: WorkspaceNode, env: string): string {
    const resId = this._sanitizeId(node.id);
    return `resource "aws_elasticache_cluster" "${resId}" {
  cluster_id           = "${resId}-${env}"
  engine               = "redis"
  node_type            = "cache.r6g.xlarge"
  num_cache_nodes      = 2
  parameter_group_name = "default.redis7"
  port                 = 6379
}
`;
  }

  private _buildWafGuardrailHcl(node: WorkspaceNode, env: string): string {
    const resId = this._sanitizeId(node.id);
    return `resource "aws_wafv2_web_acl" "${resId}" {
  name        = "${resId}-${env}"
  description = "Guardrail against adversarial injection"
  scope       = "REGIONAL"
  default_action { allow {} }
  visibility_config {
    cloudwatch_metrics_enabled = true
    metric_name                = "${resId}Metrics"
    sampled_requests_enabled   = true
  }
}
`;
  }

  private _buildGenericInstanceHcl(node: WorkspaceNode, env: string): string {
    const resId = this._sanitizeId(node.id);
    return `resource "aws_instance" "${resId}" {
  ami           = "ami-0c55b159cbfafe1f0"
  instance_type = "t3.medium"
  tags = {
    Name        = "${node.data.label}"
    Environment = "${env}"
  }
}
`;
  }

  private _generateOutputs(document: WorkspaceDocument): string {
    const outputs = document.nodes.map((n) => {
      const resId = this._sanitizeId(n.id);
      return `output "${resId}_id" {\n  value = aws_instance.${resId}.id\n}`;
    });
    return outputs.join('\n\n');
  }

  private _sanitizeId(rawId: string): string {
    return rawId.toLowerCase().replace(/[^a-z0-9_]/g, '_');
  }
}

